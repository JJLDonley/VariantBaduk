/** The board for a preset, as a fresh copy the caller can edit. */
export function presetGoban(id: string): CustomGoban | undefined {
  const preset = GOBAN_PRESETS.find((candidate) => candidate.id === id);
  return preset ? gobanFromRows(preset.rows) : undefined;
}

/** The preset a board was made from, if its shape still matches one exactly. */
export function matchingPresetId(goban: CustomGoban): string | undefined {
  return GOBAN_PRESETS.find((preset) => {
    const candidate = gobanFromRows(preset.rows);
    return candidate.width === goban.width && candidate.height === goban.height &&
      candidate.points.every((point, index) => point === goban.points[index]);
  })?.id;
}

export function gobanFromRows(rows: readonly string[]): CustomGoban {
  const width = Math.max(...rows.map((row) => row.length));
  const points: number[] = [];
  const starPoints: Array<{ x: number; y: number }> = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < width; x++) {
      const cell = row[x] ?? ".";
      points.push(cell === "." ? -1 : 0);
      if (cell === "*") starPoints.push({ x, y });
    }
  });
  return { width, height: rows.length, points, ...(starPoints.length ? { starPoints } : {}) };
}
